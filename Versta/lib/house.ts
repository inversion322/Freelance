export function estimate(project: Project, pkg: Package['id'], opts: string[]) {
  const p = packages.find((x) => x.id === pkg)!;
  let k = p.k;
  for (const id of opts) { const o = options.find((x) => x.id === id); if (o) k += o.delta; }
  const mid = project.base * k;
  const round = (n: number) => Math.round(n / 50_000) * 50_000;
  // вилка ±6 %: геология и состояние участка до выезда инженера неизвестны
  return { from: round(mid * 0.94), to: round(mid * 1.06), perM2: Math.round(mid / project.area / 1000) * 1000 };
}

