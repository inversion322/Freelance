/** Вилка по сценарию и ответам. Всегда диапазон, никогда точная сумма. */
export function estimate(scenarioId: Scenario['id'], answers: Record<string, string>) {
  const s = scenarios.find((x) => x.id === scenarioId)!;
  let k = 1;
  for (const step of quiz) {
    const a = step.options.find((o) => o.id === answers[step.id]);
    if (a) k += a.delta;
  }
  const round = (n: number) => Math.round(n / 5000) * 5000;
  return { from: round(s.from * k), to: round(s.to * k) };
}

